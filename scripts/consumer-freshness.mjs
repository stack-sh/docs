import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const skillPath = 'skills/stack-diagrams/SKILL.md';

export function compareConsumer(expected, actual, kind) {
  assert.ok(['cli', 'web', 'production'].includes(kind));
  assert.equal(expected.schemaVersion, '1.0');
  assert.equal(actual.schemaVersion, '1.0', 'Unsupported consumer manifest');
  assert.deepEqual(actual.cli, expected.cli, `${kind}: published CLI identity is stale`);
  const select = manifest => {
    assert.ok(Array.isArray(manifest.files));
    const files = manifest.files.filter(file => kind === 'cli' ? file.path === skillPath : file.path.startsWith('site/') || file.path === skillPath);
    assert.ok(files.length > 0);
    const sorted = files.map(file => {
      assert.match(file.sha256, /^[a-f0-9]{64}$/);
      return [file.path, file.sha256];
    }).sort(([a], [b]) => a.localeCompare(b));
    assert.equal(new Set(sorted.map(([file]) => file)).size, sorted.length, 'Duplicate manifest entry');
    return sorted;
  };
  assert.deepEqual(select(actual), select(expected), `${kind}: generated Docs content is stale; update the consumer pin`);
}

async function get(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(15_000), cache: 'no-store' });
  assert.ok(response.ok, `Freshness resource unavailable: ${url} (HTTP ${response.status})`);
  return Buffer.from(await response.arrayBuffer());
}

export async function readPinnedManifest(lock, fetchBytes = get) {
  assert.equal(lock.repository, 'stack-sh/docs');
  assert.match(lock.revision, /^[a-f0-9]{40}$/);
  assert.match(lock.manifestSha256, /^[a-f0-9]{64}$/);
  const bytes = await fetchBytes(`https://raw.githubusercontent.com/stack-sh/docs/${lock.revision}/generated/manifest.json`);
  assert.equal(digest(bytes), lock.manifestSha256, 'Consumer manifest integrity mismatch');
  return JSON.parse(bytes.toString('utf8'));
}

export async function auditConsumers(expected, fetchBytes = get) {
  const targets = [
    ['cli', 'https://raw.githubusercontent.com/stack-sh/cli/main/skills/docs-source.json'],
    ['web', 'https://raw.githubusercontent.com/stack-sh/web/main/scripts/docs-source.json'],
    ['production', 'https://stack-diagram.com/docs-source.json'],
  ];
  const errors = [];
  for (const [kind, url] of targets) {
    try {
      const lock = JSON.parse((await fetchBytes(url)).toString('utf8'));
      const actual = await readPinnedManifest(lock, fetchBytes);
      compareConsumer(expected, actual, kind);
      if (kind === 'cli') {
        const skill = await fetchBytes('https://raw.githubusercontent.com/stack-sh/cli/main/skills/stack-diagrams/SKILL.md');
        assert.equal(digest(skill), expected.files.find(file => file.path === skillPath).sha256, 'CLI skill differs from the canonical generated bytes');
      }
      console.log(`${kind}: canonical generated content is current (${lock.revision}).`);
    } catch (error) {
      errors.push(`${kind}: ${error.message}`);
    }
  }
  if (errors.length) throw new Error(errors.join('\n'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = JSON.parse(await readFile(new URL('../generated/manifest.json', import.meta.url), 'utf8'));
  await auditConsumers(expected);
}
